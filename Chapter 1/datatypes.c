#include<stdio.h>
int main()
{
    int a = 10;
    float b = 6.78;
    char c = 'P';
    printf("Value of a is %d\n",a);
    printf("Value of b is %f\n",b);
    printf("Value of c is %c\n",c);
    return 0;
}
// Some keyword like float, int, char, sizeof, return, void etc. can't be used as variable name.
// %d used for integer
// %f is used for float
// %c is used for character